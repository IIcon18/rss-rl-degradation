"""Физические ограничения продольного движения, общие для всех машин.

J_MAX — предел рывка (скорости изменения ускорения), м/с^3. Ускорение
любой машины (агента, фильтра, нарушителя, фона) за шаг симуляции dt
меняется не больше чем на J_MAX·dt. Это предел исполнительной системы
(тормоза не набирают давление мгновенно), а не предпочтение водителя.
Значение 10 м/с^3 — порядок рывка обычного водителя при экстренном
торможении (≈ 11 м/с^3 у среднего водителя, 20 м/с^3 у базовой системы AEB,
Applus IDIADA, The BRAKE Report, 2019). Комфортный рывок (≈ 2–3 м/с^3,
Hoberock, 1976: рывок выше 2,94 м/с^3 вряд ли приемлем для пассажиров)
как жесткий предел не берем: он описывает спокойную езду, а в
экстренных ситуациях водители и системы его превышают.

A_PHYS_BRAKE — физический предел торможения легкового автомобиля с ABS на
сухом асфальте, м/с^2. Измерения: 0,87–1,08 g = 8,5–10,6 м/с^2
(Miller et al., SAE 2023-01-0616), 8–8,5 м/с^2 (Greibe, Trafitec, 2007).
Берем 8 м/с^2 — консервативно, нижний край измерений. Им пользуется только
экстренный режим фильтра.
"""

J_MAX = 10.0  # м/с^3
A_PHYS_BRAKE = 8.0  # м/с^2


def limit_jerk(a_target, a_prev, dt, j_max=None):
    """Ускорение на этом шаге: ближайшее к a_target, отличающееся от
    ускорения прошлого шага a_prev не больше чем на j_max·dt.
    j_max по умолчанию — J_MAX этого модуля на момент вызова (в тестах его
    можно заменить на math.inf, чтобы проверить логику без рывка)."""
    step = (J_MAX if j_max is None else j_max) * dt
    return min(max(a_target, a_prev - step), a_prev + step)
